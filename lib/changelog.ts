export const UPDATE_NEW_DAYS = 30; // 公開から何日間を「新しい更新」として、未読の数に数えるか

// 未読の更新の数（最後に見た id より新しく、公開から UPDATE_NEW_DAYS 日以内のもの）
export function countUnreadUpdates(seenId: string, today: string): number {
  const limit = new Date(today + 'T00:00:00');
  limit.setDate(limit.getDate() - UPDATE_NEW_DAYS);
  const cutoff = limit.toISOString().slice(0, 10);
  return UPDATES.filter((u) => u.id > seenId && u.date >= cutoff).length;
}
